const pipeOutputConsistency: DoctorCheck = {
  id: "PIPE-004",
  category: "Pipeline Health",
  run(): DoctorResult {
    const products = readJson<{ data: Record<string, unknown>[]; _metadata: Record<string, unknown> }>(path.resolve("src/content/products.json"));
    const collections = readJson<{ data: Record<string, unknown>[] }>(path.resolve("src/content/collections.json"));
    const forms = readJson<{ data: Record<string, unknown>[] }>(path.resolve("src/content/forms.json"));
    const issues: string[] = [];
    if (!products || !collections || !forms) {
      return { id: "PIPE-004", category: "Pipeline Health", status: "FAIL", summary: "Cannot verify consistency; data files missing.", recommendation: "Run the data import pipeline." };
    }
    if (products.data.length === 0) {
      issues.push("Products dataset is empty.");
    }
    if (collections.data.length === 0) {
      issues.push("Collections dataset is empty.");
    }
    if (forms.data.length === 0) {
      issues.push("Forms dataset is empty.");
    }
    const validFormIds = new Set(forms.data.map((f) => String(f.id || "")));
    for (const p of products.data) {
      const formId = p.formId as string | undefined;
      if (formId && !validFormIds.has(formId)) {
        issues.push("Product " + p.id + " references unknown form: " + formId);
      }
    }
    const businessAreas = new Set(products.data.map((p) => String(p.businessArea || "")));
    for (const c of collections.data) {
      const ba = c.businessArea as string | undefined;
      if (ba && ba !== "null" && !businessAreas.has(ba)) {
        issues.push("Collection " + c.id + " has businessArea not found in any product: " + ba);
      }
    }
    if (issues.length === 0) {
      return { id: "PIPE-004", category: "Pipeline Health", status: "PASS", summary: "Pipeline output is consistent across all datasets." };
    }
    return {
      id: "PIPE-004", category: "Pipeline Health", status: "WARN",
      summary: issues.length + " consistency issue(s) found.",
      details: issues,
      recommendation: "Review cross-dataset references and re-run the pipeline.",
    };
  },
};

