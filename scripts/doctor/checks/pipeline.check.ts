const pipeGeneratedData: DoctorCheck = {
  id: "PIPE-002",
  category: "Pipeline Health",
  run(): DoctorResult {
    const files = [
      { file: "src/content/products.json", name: "products" },
      { file: "src/content/collections.json", name: "collections" },
      { file: "src/content/forms.json", name: "forms" },
    ];
    const issues: string[] = [];
    for (const { file, name } of files) {
      const fullPath = path.resolve(file);
      if (!fs.existsSync(fullPath)) {
        issues.push(name + ".json is missing.");
        continue;
      }
      const parsed = readJson<Record<string, unknown>>(fullPath);
      if (!parsed) {
        issues.push(name + ".json is not valid JSON.");
        continue;
      }
      const meta = parsed._metadata as Record<string, unknown> | undefined;
      if (!meta || meta.generated !== true) {
        issues.push(name + ".json was not generated by the pipeline.");
        continue;
      }
      if (!Array.isArray(parsed.data) || parsed.data.length === 0) {
        issues.push(name + ".json has an empty data array.");
      }
    }
    if (issues.length === 0) {
      return { id: "PIPE-002", category: "Pipeline Health", status: "PASS", summary: "All generated data files are available and valid." };
    }
    return {
      id: "PIPE-002", category: "Pipeline Health", status: "FAIL",
      summary: "Generated content data issues found.",
      details: issues,
      recommendation: "Run the data import pipeline to regenerate data.",
    };
  },
};

